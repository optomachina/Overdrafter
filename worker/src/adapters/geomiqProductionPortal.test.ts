type Page = Record<string, { count?: number; text?: string | null }>;

function reader(page: Page): ProviderPortalReadCapability {
  return {
    count: async (selector) => page[selector]?.count ?? (page[selector]?.text ? 1 : 0),
    readText: async (selector) => page[selector]?.text ?? null,
    readTexts: async (selector) => (page[selector]?.text ? [page[selector].text!] : []),
    readAttribute: async () => null,
  };
}

/** Model a kernel read that waits for an absent optional field while the page changes. */
function delayedReader(page: Page, shouldDelay: (selector: string) => boolean, change: () => void): ProviderPortalReadCapability {
  const base = reader(page);
  return {
    ...base,
    readText: async (selector) => {
      if (shouldDelay(selector)) {
        await new Promise((resolve) => setTimeout(resolve, 5_000));
        change();
      }
      return base.readText(selector);
    },
  };
}

