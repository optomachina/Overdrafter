// @vitest-environment node
import fs from "node:fs/promises";
import { afterEach, describe, expect, it, vi } from "vitest";
import type { VendorQuoteAdapterInput, WorkerConfig } from "../types";
import {
  registerProductionPortalAuthorizationRefusals,
  type ProductionPortalDefaultDenyHarness,
} from "../../test-support/productionPortalDefaultDeny";
import { quickpartsDispatchAuthorization, quickpartsDispatchEnvelope } from "../../test-support/quickpartsDispatchFixture";
import { observedLiveConfig, productionCadStager } from "../../test-support/productionPortalTestHarness";
import { geomiqDispatchAuthorization, geomiqDispatchEnvelope } from "../../test-support/geomiqDispatchFixture";
import { GEOMIQ_DISPATCH_ENVELOPE, geomiqDispatchAuthorizationDenial } from "./geomiqDispatchAuthorization";
import { buildGeomiqProductionPortalDefinition } from "./geomiqProductionPortal";
import { runProviderPortalKernel } from "./providerPortalKernel";

/**
 * Generated by `npm run fixture:onboard -- geomiq --stage=live` (OVD-687).
 *
 * The generated Geomiq production stub is default-off: without a
 * current provider-dispatch authorization for its envelope, bound to the
 * staged bytes and quantity, there is zero provider interaction; with one, the
 * stub still stops as unavailable before any session read. Synthetic data only.
 */

const tempDirs: string[] = [];
afterEach(async () => {
  vi.restoreAllMocks();
  await Promise.all(tempDirs.splice(0).map((dir) => fs.rm(dir, { recursive: true, force: true })));
});

const observedConfig = () => observedLiveConfig("geomiq");
const stagedCad = productionCadStager("geomiq", tempDirs);

async function authorizedInput(overrides: Partial<VendorQuoteAdapterInput> = {}): Promise<VendorQuoteAdapterInput> {
  const cad = await stagedCad();
  const envelope = geomiqDispatchEnvelope({ cadSha256: cad.trustedContentSha256, requestedQuantity: 3 });
  return {
    organizationId: envelope.subject.organizationId,
    quoteRunId: envelope.task.quoteRunId,
    requestedQuantity: 3,
    executionContext: "production_dispatch",
    stagedCadFile: cad,
    stagedDrawingFile: null,
    providerDispatchAuthorization: geomiqDispatchAuthorization(envelope),
    ...overrides,
  } as unknown as VendorQuoteAdapterInput;
}

function defaultDenyHarness(): ProductionPortalDefaultDenyHarness {
  return {
    vendor: "geomiq",
    envelopeId: GEOMIQ_DISPATCH_ENVELOPE.id,
    taskId: "00000000-0000-4000-8000-2ba9f55c660b",
    vendorQuoteResultId: "00000000-0000-4000-8000-2ba9f55c6609",
    claimedAt: "2026-10-10T12:04:00.000Z",
    unauthorizedCadName: "part.sldprt",
    otherProviderAuthorization: (input: VendorQuoteAdapterInput) =>
      quickpartsDispatchAuthorization(quickpartsDispatchEnvelope({
        cadSha256: input.stagedCadFile!.trustedContentSha256!,
        requestedQuantity: 3,
      })),
    buildDefinition: buildGeomiqProductionPortalDefinition,
    observedConfig,
    authorizedInput,
    stagedCad,
  };
}

describe("Geomiq generated production stub (fixture:onboard)", () => {
  it("declares its envelope on the production portal definition", () => {
    expect(buildGeomiqProductionPortalDefinition().productionDispatch).toEqual({
      envelope: { ...GEOMIQ_DISPATCH_ENVELOPE },
    });
  });

  it("accepts exactly the authorized bytes and quantity at the adapter seam", async () => {
    expect(geomiqDispatchAuthorizationDenial(await authorizedInput())).toBeNull();
  });

  it("stays unavailable before any session read or launch even when authorized", async () => {
    const { config, sessionRead } = observedConfig();
    const launchBrowser = vi.fn();
    await expect(runProviderPortalKernel(buildGeomiqProductionPortalDefinition(), config, await authorizedInput(), { launchBrowser }))
      .resolves.toMatchObject({ state: "unavailable", reason: "geomiq_reviewed_portal_evidence_missing", providerMutationPossible: false });
    expect(launchBrowser).not.toHaveBeenCalled();
    expect(sessionRead).not.toHaveBeenCalled();
  });
});

describe("Geomiq production branch default-deny (fixture:onboard)", () => {
  registerProductionPortalAuthorizationRefusals(defaultDenyHarness());
});
