/** Deterministic, committed stdin fixtures; never executes SQL or contacts a DB. */
import { createHash } from "node:crypto";
import { existsSync, lstatSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const target = "supabase/fixtures/free-quote-qualification";
const entries = [
  ["supabase/tests/free_quote_job_meter.sql", "free-quote-job-meter.expanded.sql"],
  ["supabase/tests/free_confirmed_quote_access.sql", "free-confirmed-quote-access.expanded.sql"],
  ["scripts/qualification/free-quote-terminal-lifecycle.sql", "free-quote-terminal-lifecycle.expanded.sql"],
];
const flags = new Set(process.argv.slice(2));
const allowed = new Set(["--check", "--write-source"]);
if ([...flags].some((argument) => !allowed.has(argument))) {
  throw new Error("Only --check and --write-source are supported.");
}
if (flags.has("--check") && flags.has("--write-source")) {
  throw new Error("--check and --write-source are mutually exclusive.");
}
const check = flags.has("--check");
const writeSource = flags.has("--write-source");
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");

function expand(relativePath, ancestors = []) {
  const absolute = path.resolve(root, relativePath);
  const relative = path.relative(root, absolute);
  if (relative.startsWith("..") || path.isAbsolute(relative) || ancestors.includes(relative) || lstatSync(absolute).isSymbolicLink()) {
    throw new Error("Fixture include escapes source or is cyclic/symlinked.");
  }
  return readFileSync(absolute, "utf8").replace(/^\s*\\ir\s+([^\n]+)$/gm, (_line, include) => {
    const included = path.relative(root, path.resolve(path.dirname(absolute), include.trim().replace(/^['"]|['"]$/g, "")));
    const content = expand(included, [...ancestors, relative]);
    const digest = hash(readFileSync(path.join(root, included)));
    return `-- BEGIN exact include ${included} SHA-256 ${digest}\n${content}\n-- END exact include ${included}`;
  });
}

if (!writeSource) {
  mkdirSync(path.join(root, target), { recursive: true });
  for (const [source, name] of entries) {
    const content = `-- Generated by scripts/generate-free-quote-fixtures.mjs; do not edit.\n-- Source: ${source} SHA-256 ${hash(readFileSync(path.join(root, source)))}\n\\set ON_ERROR_STOP on\nset search_path=public,extensions;\nset statement_timeout='45s';\nset lock_timeout='5s';\n${expand(source)}`;
    const destinations = [path.join(root, target, name)];
    // Supabase CLI stages tests independently of scripts/. A generated standalone
    // discovery entry keeps the exact reviewed body usable in that isolated tree.
    if (name === "free-quote-terminal-lifecycle.expanded.sql") {
      destinations.push(path.join(root, "supabase/tests/free_quote_terminal_lifecycle.sql"));
    }
    for (const destination of destinations) {
      if (check) {
        if (!existsSync(destination) || readFileSync(destination, "utf8") !== content) {
          throw new Error(`Generated fixture drift: ${path.relative(root, destination)}`);
        }
      } else writeFileSync(destination, content);
    }
  }
  console.log(`Three source-only SQL fixtures ${check ? "verified" : "generated"}; no SQL executed.`);
} else {
  const {
    SOURCE_PATH,
    applyDerivedFreeQuoteMigrationPins,
    deriveFreeQuoteMigrationPins,
  } = await import("./free-quote-ci-profile.mjs");
  const sourcePath = path.join(root, SOURCE_PATH);
  const manifest = JSON.parse(readFileSync(sourcePath, "utf8"));
  const next = applyDerivedFreeQuoteMigrationPins(manifest, deriveFreeQuoteMigrationPins(root));
  writeFileSync(sourcePath, `${JSON.stringify(next, null, 2)}\n`);
  console.log(`Regenerated ${SOURCE_PATH} from the migrations directory; generated output stays opt-in.`);
}
