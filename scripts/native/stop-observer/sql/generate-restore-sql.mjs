/** Generate the paired OVD-649 restoration SQL from the OVD-575 migration and
 * the staged replacement. Usage: node <this file> [--check]. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../../../..", import.meta.url)));
export const migrationPath = "supabase/migrations/20260927130000_ovd575_native_observer_registry.sql";
export const replacementPath = "scripts/native/stop-observer/sql/store-native-observer-evidence-replay.staged.sql";
export const restorePath = "scripts/native/stop-observer/sql/store-native-observer-evidence-restore.staged.sql";
const signature = "engineering_private.store_native_observer_evidence(uuid,bytea,bytea)";
const header = "create function engineering_private.store_native_observer_evidence(\n";
const sha256 = (value) => createHash("sha256").update(value, "utf8").digest("hex");

/** The single OVD-575 definition, from its create line through the closing `$$;`. */
function originalDefinition(migration) {
  const start = migration.indexOf(header);
  if (start < 0 || migration.includes(header, start + 1)) throw new Error("ovd649_original_definition_not_unique");
  const end = migration.indexOf("\n$$;\n", start);
  if (end < 0) throw new Error("ovd649_original_definition_unterminated");
  return migration.slice(start, end + 4);
}
/** prosrc is exactly the text between the `as $$` opener and the closing `$$`. */
function body(definition) {
  const match = /\) returns uuid language plpgsql security definer set search_path = '' as \$\$([\s\S]*)\$\$;$/.exec(definition);
  if (!match || match[1].includes("$$")) throw new Error("ovd649_definition_shape_drift");
  return match[1];
}

export function buildRestoreSql(read = (path) => readFileSync(resolve(root, path), "utf8")) {
  const replacement = read(replacementPath);
  const original = originalDefinition(read(migrationPath));
  const replacementStart = replacement.indexOf(header.replace("create function", "create or replace function"));
  if (replacementStart < 0) throw new Error("ovd649_replacement_shape_drift");
  const replacementBody = body(replacement.slice(replacementStart).trimEnd());
  const originalBody = body(original);
  if (replacementBody === originalBody) throw new Error("ovd649_replacement_equals_original");
  const restoreTag = "$ovd649_restore_definition$";
  if (original.includes(restoreTag)) throw new Error("ovd649_restore_tag_collision");
  const pins = { replacementSha256: sha256(replacement), replacementBodySha256: sha256(replacementBody),
    originalBodySha256: sha256(originalBody) };
  const sql = `-- STAGED SOURCE ONLY. Paired restoration for
-- ${replacementPath}.
-- Generated by scripts/native/stop-observer/sql/generate-restore-sql.mjs; do not edit.
-- Exact replacement SQL SHA-256: ${pins.replacementSha256}
-- Restores the OVD-575 body from ${migrationPath}
-- with create or replace, which keeps the function OID, owner and grants. The
-- prior body, signature, security definer and search_path are restored byte
-- for byte, so the catalog digest returns to its value before the replacement.
-- Window 2 rollback runs this first, before any OVD-619 or OVD-558 reverse:
-- see docs/release/ovd-649-window-2-order.md.
-- READ COMMITTED, then the shared OVD-510 advisory lock, then the preflight.
-- The preflight refuses unless the live body is exactly the staged replacement.
begin;
set local statement_timeout = '60s';
set local lock_timeout = '10s';
do $ovd649_restore_isolation$
begin
  if current_setting('transaction_isolation') <> 'read committed' then
    raise exception 'ovd649_restore_read_committed_required' using errcode = '0A000';
  end if;
end $ovd649_restore_isolation$;
select pg_advisory_xact_lock(510, 2);
do $ovd649_restore$
declare
  v_oid oid := to_regprocedure('${signature}');
  v_before record;
  v_after record;
begin
  if v_oid is null or (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'engineering_private' and p.proname = 'store_native_observer_evidence') <> 1 then
    raise exception 'ovd649_restore_function_missing_or_overloaded';
  end if;
  select encode(sha256(convert_to(p.prosrc, 'UTF8')), 'hex') as body_sha256, p.prosecdef, p.proconfig, pg_get_userbyid(p.proowner) as owner,
      p.proacl::text as acl, p.prokind, p.proretset, p.prorettype, l.lanname
    into v_before from pg_proc p join pg_language l on l.oid = p.prolang where p.oid = v_oid;
  if v_before.body_sha256 <> '${pins.replacementBodySha256}'
     or not v_before.prosecdef or v_before.proconfig is distinct from array['search_path=""']
     or v_before.owner <> 'postgres' or v_before.prokind <> 'f' or v_before.proretset
     or v_before.prorettype <> 'uuid'::regtype or v_before.lanname <> 'plpgsql'
     or exists (select 1 from pg_proc p cross join lateral aclexplode(p.proacl) a
       where p.oid = v_oid and a.grantee not in (p.proowner, 'ovd575_observer_validator'::regrole)) then
    raise exception 'ovd649_restore_unexpected_current_state:%', v_before.body_sha256;
  end if;
  execute ${restoreTag}${original.replace("create function", "create or replace function")}${restoreTag};
  select encode(sha256(convert_to(p.prosrc, 'UTF8')), 'hex') as body_sha256, p.prosecdef, p.proconfig, pg_get_userbyid(p.proowner) as owner,
      p.proacl::text as acl, p.prokind, p.proretset, p.prorettype, l.lanname
    into v_after from pg_proc p join pg_language l on l.oid = p.prolang where p.oid = v_oid;
  if v_after.body_sha256 <> '${pins.originalBodySha256}'
     or (v_after.prosecdef, v_after.proconfig, v_after.owner, v_after.acl, v_after.prokind,
         v_after.proretset, v_after.prorettype, v_after.lanname)
       is distinct from (v_before.prosecdef, v_before.proconfig, v_before.owner, v_before.acl,
         v_before.prokind, v_before.proretset, v_before.prorettype, v_before.lanname) then
    raise exception 'ovd649_restore_postflight_mismatch:%', v_after.body_sha256;
  end if;
end $ovd649_restore$;
commit;
`;
  return { sql, pins };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check")) throw new Error("ovd649_unsupported_argument");
  const { sql, pins } = buildRestoreSql();
  if (args.includes("--check")) {
    if (readFileSync(resolve(root, restorePath), "utf8") !== sql) throw new Error("ovd649_restore_source_drift");
  } else {
    writeFileSync(resolve(root, restorePath), sql);
  }
  process.stdout.write(JSON.stringify({ restoreSha256: sha256(sql), ...pins }) + "\n");
}
