// OVD-736: anon/authenticated function EXECUTE allowlist tooling.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

export const ALLOWLIST_PATH = 'supabase/security/function-execute-allowlist.json';
export const PGTAP_PATH = 'supabase/tests/pending/ovd736_function_execute_allowlist.sql.pending';

export function loadAllowlist(root) {
  return JSON.parse(readFileSync(join(root, ALLOWLIST_PATH), 'utf8'));
}

const q = (s) => `'${s.replaceAll("'", "''")}'`;

export function renderPgTap(allowlist) {
  const expected = [
    ...allowlist.anon.map((e) => ['anon', e.signature]),
    ...allowlist.authenticated.map((e) => ['authenticated', e.signature]),
  ];
  const values = expected.map(([r, s]) => `    (${q(r)}, ${q(s)})`).join(',\n');
  return `-- GENERATED by scripts/function-execute-allowlist.mjs from ${ALLOWLIST_PATH}. Do not edit.
-- OVD-736: parked (.pending) until docs/migration-drafts/ovd-736-revoke-anon-execute.sql
-- lands in an approved window; then move to supabase/tests/*.sql.
begin;

create extension if not exists pgtap with schema extensions;

select plan(3);

create temporary table ovd736_actual on commit drop as
select r.role, p.proname || '(' || oidvectortypes(p.proargtypes) || ')' as signature
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
cross join (values ('anon'), ('authenticated')) as r(role)
where n.nspname = 'public'
  and p.prokind = 'f'
  and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  and has_function_privilege(r.role, p.oid, 'EXECUTE');

create temporary table ovd736_expected (role text, signature text) on commit drop;
${expected.length ? `insert into ovd736_expected (role, signature) values\n${values};` : ''}

select set_eq(
  'select role, signature from ovd736_actual',
  'select role, signature from ovd736_expected',
  'anon/authenticated EXECUTE on public functions matches supabase/security/function-execute-allowlist.json'
);

select is_empty(
  $$select signature from ovd736_actual where role = 'anon'
    except select signature from ovd736_expected where role = 'anon'$$,
  'anon executes no public function outside the reviewed anon allowlist'
);

select is_empty(
  $$select p.oid::regprocedure::text from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind = 'f' and p.proconfig is null
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')$$,
  'every public function pins search_path'
);

select * from finish();

rollback;
`;
}

export function migrationFunctionNames(root) {
  const dir = join(root, 'supabase/migrations');
  const names = new Set();
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.sql'))) {
    const sql = readFileSync(join(dir, f), 'utf8');
    for (const m of sql.matchAll(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.|"public"\.)?"?([a-z_0-9]+)"?\s*\(/gi)) {
      names.add(m[1].toLowerCase());
    }
  }
  return names;
}

if (process.argv[2] === '--write') {
  const { writeFileSync } = await import('node:fs');
  const root = process.cwd();
  writeFileSync(join(root, PGTAP_PATH), renderPgTap(loadAllowlist(root)));
}
