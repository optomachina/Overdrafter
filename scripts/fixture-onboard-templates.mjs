export function pascalCase(key) {
  return `${key.charAt(0).toUpperCase()}${key.slice(1)}`;
}

export function constantCase(key) {
  return key.toUpperCase();
}

export function dispatchEnvelopeId(key) {
  return `${key}-quote-envelope`;
}

/** Stable per-provider synthetic UUIDs, so two providers' fixtures never collide. */
export function syntheticUuid(key, index) {
  const prefix = createHash("sha256").update(`fixture:onboard:${key}`).digest("hex").slice(0, 10);
  return `00000000-0000-4000-8000-${prefix}${index.toString(16).padStart(2, "0")}`;
}

export function allowedHosts(manifest) {
  const hosts = new Set(manifest.official.domains);
  for (const url of manifest.official.urls) {
    hosts.add(new URL(url).hostname);
  }
  return [...hosts].sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
}

export function cadExtensions(manifest) {
  return [...manifest.capabilityEnvelope.files.values];
}

export function unauthorizedCadExtension(manifest) {
  const supported = new Set(cadExtensions(manifest));
  return UNAUTHORIZED_CAD_CANDIDATES.find((extension) => !supported.has(extension));
}

function generatedBanner(key, stage) {
  return `Generated by \`npm run fixture:onboard -- ${key} --stage=${stage}\` (${GENERATOR_ISSUE}).`;
}

