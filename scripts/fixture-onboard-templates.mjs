/**
 * Deterministic templates for `fixture:onboard --stage=live|admit` (OVD-687).
 * Every template is a pure function of the provider manifest and the explicit
 * options; none reads the clock, the network, or a credential. All output is
 * default-off: nothing generated here admits, routes, or enables a provider.
 */

export const GENERATOR_ISSUE = "OVD-687";
