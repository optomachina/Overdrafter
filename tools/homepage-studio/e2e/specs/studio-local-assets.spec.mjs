// B. Figure assets in the local studio: corner icons, generation with the demo engine, versions, blocked and failed states.
import { test, expect } from "../helpers/fixtures.mjs";
import { VIEWPORTS, DESKTOP, TABLET, PHONE } from "../helpers/viewports.mjs";
import { expectAppendOnly } from "../helpers/versions.mjs";
import { generateDemo, submitJob, waitFinal } from "../helpers/jobs.mjs";

const NOT_LOGGED_IN = "Claude CLI is not logged in: run `claude auth login`";

async function activateChapter(sp, c) {
  const art = sp.frame.locator(`article.chap[data-c="${c}"]`);
  await art.evaluate((el) => el.scrollIntoView({ block: "center" }));
  await expect(art).toHaveClass(/is-active/);
}

for (const vp of VIEWPORTS) {
  test.describe(`figure corner icons, ${vp.name}`, { tag: ["@studio-local"] }, () => {
    test.use({ viewport: vp.viewport, hasTouch: vp.touch });

    test("the hero and all seven chapter figures carry a history icon and a sparkle icon", async ({ sp }) => {
      await sp.open();
      const sections = [["Hero", null], ...Array.from({ length: 7 }, (_, i) => [`Chapter ${i + 1}`, i])];
      for (const [label, chapter] of sections) {
        if (chapter !== null) await activateChapter(sp, chapter);
        const hist = sp.historyIcon(label);
        const spark = sp.sparkleIcon(label);
        await expect(hist, `${label} history icon`).toBeVisible();
        await expect(spark, `${label} sparkle icon`).toBeVisible();
        for (const icon of [hist, spark]) {
          const box = await icon.boundingBox();
          expect(box.width, `${label} tap target width`).toBeGreaterThanOrEqual(44);
          expect(box.height, `${label} tap target height`).toBeGreaterThanOrEqual(44);
        }
      }
    });
  });
}

test.describe("generation with the demo engine (desktop)", { tag: ["@studio-local"] }, () => {
  test.use({ viewport: DESKTOP.viewport });

  test("generate from the sheet: queued, succeeded, the figure is replaced and the icons stay on top", async ({ sp, page }) => {
    await sp.open();
    const before = await sp.asset("hero");
    expect(before.versions).toHaveLength(0);
    await expect(sp.frame.locator('iframe[title^="Generated figure"]')).toHaveCount(0);
    await sp.sparkleIcon("Hero").click();
    await expect(page.locator("#sheetTitle")).toHaveText("Generate figure: Hero");
    await page.locator("#genPrompt").fill("A bracket on a bench");
    sp.studio.gate.hold(); // keep the job in flight so the in-flight state can be observed
    await page.locator("#genGo").click();
    const status = page.locator("#job-asset-hero .status");
    await expect(status).toHaveAttribute("data-state", "queued");
    await expect(status).toContainText("Queued");
    await expect.poll(() => sp.studio.gate.entered).toBe(1);
    sp.studio.gate.release();
    await expect(status).toHaveAttribute("data-state", "succeeded", { timeout: 20_000 });
    await expect(status).toContainText("demo engine, not generated by a model");
    await expect(page.locator("#toast")).toContainText("New figure version saved for Hero.");
    const after = await sp.asset("hero");
    expect(after.versions).toHaveLength(1);
    expectAppendOnly(before, after);
    expect(after.versions[0]).toMatchObject({ kind: "generated", engine: "template-demo", tool: "hand-built", prompt: "A bracket on a bench" });
    // The figure area now shows the generated asset in a nested, sandboxed frame (allow-scripts only).
    const gen = sp.frame.locator('iframe[title="Generated figure, Hero"]');
    await expect(gen).toBeVisible();
    await expect(gen).toHaveAttribute("sandbox", "allow-scripts");
    expect(await gen.getAttribute("sandbox")).not.toContain("allow-same-origin");
    expect(await gen.getAttribute("srcdoc")).toContain("Demo asset: Hero");
    await expect(sp.frame.locator("#heroFig")).toHaveCSS("visibility", "hidden");
    // The history icon is still on top: a real click reaches it (Playwright refuses covered targets) and opens the drawer.
    await page.locator("#sheetClose").click();
    await expect(sp.historyIcon("Hero")).toContainText("1");
    await sp.historyIcon("Hero").click();
    await expect(page.locator("#sheetTitle")).toHaveText("Figure versions: Hero");
  });

  test("a second generation keeps both; Star, Restore (a NEW version) and Show in page work", async ({ sp, page }) => {
    await sp.open();
    const first = await generateDemo(sp, "hero", "first figure");
    const second = await generateDemo(sp, "hero", "second figure");
    await page.reload();
    await sp.waitReady();
    const before = await sp.asset("hero");
    expect(before.versions.map((v) => v.id)).toEqual([first.resultVersionId, second.resultVersionId]);
    await sp.historyIcon("Hero").click();
    const rows = sp.sheet.locator("ol.versions > li");
    await expect(rows).toHaveCount(2);
    await expect(rows.first()).toContainText("second figure"); // newest first
    await expect(rows.last()).toContainText("first figure");
    // Star the older one.
    await rows.last().getByRole("button", { name: "Star" }).click();
    await expect(rows.last().getByRole("button", { name: "Unstar" })).toBeVisible();
    expect((await sp.asset("hero")).versions.find((v) => v.id === first.resultVersionId).starred).toBe(true);
    // Show the older one in the page without changing history.
    await rows.last().getByRole("button", { name: "Show in page" }).click();
    await expect(sp.frame.locator('iframe[title="Generated figure, Hero"]')).toHaveAttribute("data-version", first.resultVersionId);
    expect((await sp.asset("hero")).versions).toHaveLength(2);
    // Restore the older one: a third record appears, nothing is overwritten.
    await rows.last().getByRole("button", { name: "Restore" }).click();
    await expect(sp.sheet.locator("ol.versions > li")).toHaveCount(3);
    const after = await sp.asset("hero");
    expectAppendOnly(before, after);
    expect(after.versions.at(-1)).toMatchObject({ kind: "restore" });
    expect(after.currentVersionId).toBe(after.versions.at(-1).id);
  });

  // KNOWN PRODUCT BUG found by this suite: JobManager.submit() writes the "running" state and then the initial "queued"
  // record, and both go through the same serialized queue in that order, so the job file ends as "queued" and a job that
  // is really running is reported as "queued" by GET /api/jobs/:id for its whole run (startedAt is never stored).
  test("an in-flight local job is reported as running", async ({ sp }) => {
    await sp.open();
    sp.studio.gate.hold();
    const job = await submitJob(sp, { kind: "asset", sectionId: "hero", engine: "template-demo" });
    await expect.poll(() => sp.studio.gate.entered).toBe(1);
    await expect.poll(async () => (await (await sp.get(`/api/jobs/${job.id}`)).json()).job.state).toBe("running");
    sp.studio.gate.release();
    expect((await waitFinal(sp, job.id)).state).toBe("succeeded");
  });
});

test.describe("blocked and failed generation (desktop)", { tag: ["@studio-local"] }, () => {
  test.use({ viewport: DESKTOP.viewport });

  test("claude-cli while not logged in is BLOCKED with the exact message, creates no version, and Retry with demo engine works", async ({ sp, page }) => {
    await sp.open();
    const before = await sp.asset("hero");
    await sp.openSettings();
    await page.locator("#engine").selectOption("claude-cli");
    await expect(page.locator("#engine")).toHaveValue("claude-cli");
    await sp.closeSettings();
    await sp.sparkleIcon("Hero").click();
    await expect(page.locator("#sheet")).toContainText(NOT_LOGGED_IN);
    await page.locator("#genPrompt").fill("blocked attempt");
    await page.locator("#genGo").click();
    const status = page.locator("#job-asset-hero .status");
    await expect(status).toHaveAttribute("data-state", "blocked", { timeout: 20_000 });
    await expect(status).toContainText(NOT_LOGGED_IN);
    await expect(page.locator("#toast")).toContainText(NOT_LOGGED_IN);
    // Nothing was fabricated.
    expect((await sp.asset("hero")).versions).toHaveLength(before.versions.length);
    await expect(sp.frame.locator('iframe[title^="Generated figure"]')).toHaveCount(0);
    const jobs = (await (await sp.get(`/api/jobs?limit=5`)).json()).jobs;
    expect(jobs[0]).toMatchObject({ state: "blocked", engine: "claude-cli", message: NOT_LOGGED_IN });
    // Retry with the demo engine continues with a clearly labelled placeholder.
    await status.getByRole("button", { name: "Retry with demo engine" }).click();
    await expect(page.locator("#job-asset-hero .status")).toHaveAttribute("data-state", "succeeded", { timeout: 20_000 });
    const after = await sp.asset("hero");
    expect(after.versions).toHaveLength(before.versions.length + 1);
    expect(after.versions.at(-1)).toMatchObject({ engine: "template-demo", kind: "generated" });
    expect(after.versions.at(-1).note).toContain("demo engine, not generated by a model");
  });

  test.describe("with the CLI reported as logged in", () => {
    test.use({ studioOptions: { probe: "logged-in" } });

    test("a tool whose skill folder is missing is shown as unavailable with its specific message and its job is blocked", async ({ sp, page }) => {
      await sp.open();
      await sp.openSettings();
      await expect(page.locator("#engine")).toHaveValue("claude-cli"); // the default follows availability
      await page.locator("#tool").selectOption("anatomy");
      await expect(page.locator("#tool option[value=anatomy]")).toHaveText("Anatomy (unavailable)");
      await sp.closeSettings();
      const message = /Anatomy is unavailable: its skill folder was not found on this machine/;
      await expect(page.locator("#strip")).toContainText(message);
      await sp.sparkleIcon("Hero").click();
      await expect(page.locator("#sheet")).toContainText(message);
      await page.locator("#genGo").click();
      const status = page.locator("#job-asset-hero .status");
      await expect(status).toHaveAttribute("data-state", "blocked", { timeout: 20_000 });
      await expect(status).toContainText(message);
      expect((await sp.asset("hero")).versions).toHaveLength(0);
    });
  });

  test.describe("with a failing engine", () => {
    test.use({ studioOptions: { fakeEngine: { behavior: "fail", message: "Forced failure from the e2e fake engine" } } });

    test("a failed job creates a 'failed' version with a log, and no figure is shown", async ({ sp, page }) => {
      await sp.open();
      const job = await submitJob(sp, { kind: "asset", sectionId: "hero", engine: "fake", prompt: "this will fail" });
      const done = await waitFinal(sp, job.id);
      expect(done).toMatchObject({ state: "failed", message: "Forced failure from the e2e fake engine" });
      const asset = await sp.asset("hero");
      expect(asset.versions).toHaveLength(1);
      const v = asset.versions[0];
      expect(v).toMatchObject({ kind: "failed", engine: "fake", assetPath: null });
      expect(v.logPath).toBeTruthy();
      const log = await sp.get(`/api/log/${v.id}`);
      expect(log.status()).toBe(200);
      expect(await log.text()).toContain("fake engine: fail");
      // In the UI: the drawer lists it as failed with a log, and the page still shows its built-in figure.
      await page.reload();
      await sp.waitReady();
      await expect(sp.frame.locator('iframe[title^="Generated figure"]')).toHaveCount(0);
      await sp.historyIcon("Hero").click();
      const row = sp.sheet.locator("ol.versions > li").first();
      await expect(row.locator(".badge.bad")).toHaveText("failed");
      await expect(row.getByRole("button", { name: "Restore" })).toHaveCount(0); // a failed attempt cannot be restored
      await row.getByRole("button", { name: "Show log" }).click();
      await expect(sp.sheet.locator("#logBox")).toContainText("fake engine: fail");
    });
  });
});

test.describe("Outline view: compare two figure versions (desktop)", { tag: ["@studio-local"] }, () => {
  test.use({ viewport: DESKTOP.viewport });

  test("Compare shows both versions side by side in sandboxed frames", async ({ sp, page }) => {
    await generateDemo(sp, "hero", "outline one");
    await generateDemo(sp, "hero", "outline two");
    await sp.goto("/outline.html");
    await page.locator("#historyBtn").click();
    const rows = page.locator("#drawerList > li");
    await expect(rows).toHaveCount(2);
    await rows.nth(0).getByRole("button", { name: "Compare" }).click();
    await rows.nth(1).getByRole("button", { name: "Compare" }).click();
    const dialog = page.locator("#compare");
    await expect(dialog).toBeVisible();
    for (const id of ["#cmpFrameA", "#cmpFrameB"]) {
      await expect(dialog.locator(id)).toBeVisible();
      await expect(dialog.locator(id)).toHaveAttribute("sandbox", "allow-scripts");
      await expect(dialog.locator(id)).toHaveAttribute("src", /\/api\/preview\/asset\//);
    }
    await expect(page.locator("#cmpA")).not.toBeEmpty();
    await expect(page.locator("#cmpB")).not.toBeEmpty();
  });
});

