// Code shared by Page mode (page.js) and the Outline view (studio.js): DOM helper, JSON API client,
// theme storage, job status rendering, receipts. Talks only to /api/*; no filesystem or path knowledge.
import { wordDiff } from "/api/shared/diff.mjs";

export const FINAL = new Set(["succeeded", "failed", "blocked", "cancelled", "timed_out"]);
export const STATE_LABEL = { queued: "Queued", running: "Running", succeeded: "Succeeded", failed: "Failed", blocked: "Blocked", cancelled: "Cancelled", timed_out: "Timed out" };
export const THEME_KEY = "od-studio-theme";

export function h(tag, props = {}, ...kids) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (v === undefined || v === null || v === false) continue;
    if (k === "class") el.className = v;
    else if (k === "text") el.textContent = v;
    else if (k.startsWith("on")) el.addEventListener(k.slice(2), v);
    else if (k === "value") el.value = v;
    else el.setAttribute(k, v === true ? "" : v);
  }
  for (const kid of kids.flat()) if (kid !== undefined && kid !== null && kid !== false) el.append(kid.nodeType ? kid : document.createTextNode(String(kid)));
  return el;
}

let unauthorized = () => {};
export const onUnauthorized = (fn) => {
  unauthorized = fn;
};

export async function api(method, path, body) {
  let res;
  try {
    res = await fetch(path, { method, credentials: "same-origin", headers: body ? { "Content-Type": "application/json" } : {}, body: body ? JSON.stringify(body) : undefined });
  } catch {
    return { ok: false, status: 0, data: { message: "Network error: could not reach the studio." } };
  }
  let data = null;
  try {
    data = await res.json();
  } catch {
    /* non-json */
  }
  if (res.status === 401) unauthorized();
  return { ok: res.ok, status: res.status, data };
}

export function makeToast(host) {
  let timer;
  return (msg, bad = false) => {
    host.replaceChildren(h("p", { class: bad ? "bad" : "", text: msg }));
    clearTimeout(timer);
    timer = setTimeout(() => host.replaceChildren(), 6000);
  };
}

export const fmtTime = (iso) => {
  try {
    return new Date(iso).toLocaleString([], { dateStyle: "medium", timeStyle: "short" });
  } catch {
    return iso;
  }
};

export function receipt(v) {
  const bits = [v.engine, v.tool].filter((x) => x && x !== "none");
  let s = bits.join(" / ");
  if (v.model && v.model !== "none") s += (s ? " / " : "") + v.model;
  const cost = v.usage && v.usage.total_cost_usd;
  if (typeof cost === "number") s += ` / $${cost.toFixed(2)}`;
  return s || "manual";
}

export function readStoredTheme() {
  let t = null;
  try {
    t = localStorage.getItem(THEME_KEY);
  } catch {
    /* storage may be blocked */
  }
  if (t !== "dark" && t !== "light") t = matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
  return t;
}
export function storeTheme(t) {
  try {
    localStorage.setItem(THEME_KEY, t);
  } catch {
    /* storage may be blocked */
  }
}

export function defaultEngineId(data) {
  const pick = ["claude-cli", "github-actions", "template-demo"].find((id) => data.engines.find((e) => e.id === id && e.available));
  return pick || "template-demo";
}

export function lintHtml(res) {
  const out = [];
  for (const e of res.errors) out.push(h("p", { class: "e", text: e.message }));
  for (const w of res.warnings) out.push(h("p", { class: "w", text: w.message }));
  return out;
}

/**
 * Job status block. actions: { cancel(job), retry(job, overrides), preview(job) } (all optional).
 * The specific failure/blocked messages come from the API; nothing is rewritten here.
 */
export function renderJob(host, job, actions = {}) {
  const parts = [h("p", {}, h("span", { class: "pill", text: STATE_LABEL[job.state] || job.state }), job.demo ? " · demo engine, not generated by a model" : "", job.message ? ` · ${job.message}` : "")];
  if (job.recovery && job.state !== "succeeded") parts.push(h("p", { text: `What to do: ${job.recovery}` }));
  if (job.runUrl) parts.push(h("p", { class: "meta" }, h("a", { href: job.runUrl, target: "_blank", rel: "noopener noreferrer", text: "Open worker run" })));
  const btns = [];
  if (!FINAL.has(job.state) && job.engine !== "github-actions" && actions.cancel) btns.push(h("button", { type: "button", class: "btn", onclick: () => actions.cancel(job) }, "Cancel"));
  if (["failed", "blocked", "timed_out", "cancelled"].includes(job.state) && actions.retry) {
    btns.push(h("button", { type: "button", class: "btn", onclick: () => actions.retry(job, {}) }, "Retry"));
    if (job.engine !== "template-demo") btns.push(h("button", { type: "button", class: "btn", onclick: () => actions.retry(job, { engine: "template-demo", tool: "hand-built" }) }, "Retry with demo engine"));
  }
  if (job.state === "succeeded" && job.kind === "asset" && actions.preview) btns.push(h("button", { type: "button", class: "btn", onclick: () => actions.preview(job) }, "Preview result"));
  if (btns.length) parts.push(h("div", { class: "row" }, btns));
  if (job.log?.length) parts.push(h("details", {}, h("summary", { text: "Log" }), h("div", { class: "inner" }, h("pre", { class: "log", text: job.log.join("\n") }))));
  host.replaceChildren(h("div", { class: "status", "data-state": job.state }, parts));
}

export const jobKey = (job) => (job.kind === "copy" ? `copy:${job.fieldId}` : `asset:${job.sectionId}`);

/** Poll a job until it reaches a final state. onUpdate(job) fires on every poll, onFinal(job) once. */
export function createJobTracker({ onUpdate, onFinal }) {
  const pollers = new Map();
  function track(job) {
    onUpdate(job);
    if (FINAL.has(job.state)) {
      clearTimeout(pollers.get(job.id));
      pollers.delete(job.id);
      return onFinal(job);
    }
    clearTimeout(pollers.get(job.id));
    const delay = job.engine === "github-actions" ? 5000 : 800;
    pollers.set(job.id, setTimeout(async () => {
      const r = await api("GET", `/api/jobs/${job.id}`);
      if (r.ok) track(r.data.job);
      else if (r.status === 404) track({ ...job, state: "failed", message: "Job record not found.", recovery: "Retry." });
      else track(job);
    }, delay));
  }
  return { track, has: (id) => pollers.has(id) };
}

/**
 * One row of a copy field's append-only timeline (shared by the Outline view and the Page-mode sheet).
 * ctx: { editorText, diffOn, onDiff(), onRestore(), onStar(starred), onUsePrompt(prompt) }
 */
export function copyTimelineItem(v, ctx) {
  const failed = v.kind === "failed";
  const li = h("li", { class: v.isCurrent ? "cur" : "" },
    h("div", { class: "row" },
      h("span", { class: `badge ${failed ? "bad" : ""}`, text: v.kind }),
      v.isCurrent ? h("span", { class: "badge cur", text: "current" }) : null,
      v.starred ? h("span", { class: "badge", text: "starred" }) : null,
      h("span", { class: "meta", text: `${v.author} · ${receipt(v)} · ${fmtTime(v.createdAt)}` }),
    ),
    h("p", { class: "txt", text: failed ? `Rejected candidate: ${v.text || "(none)"}` : v.text }),
    v.prompt ? h("p", { class: "meta", text: `Prompt: ${v.prompt}` }) : null,
    v.note ? h("p", { class: "meta", text: v.note }) : null,
    v.lint?.warnings?.length ? h("p", { class: "meta", text: `Saved with warnings: ${v.lint.warnings.join(" ")}` }) : null,
  );
  if (ctx.diffOn && !failed) {
    const d = wordDiff(v.text, ctx.editorText);
    li.append(h("p", { class: "meta", text: "Changes from this version to the text in the editor:" }), h("p", { class: "diff" }, ...d.map((p) => (p.type === "ins" ? h("ins", { text: p.value }) : p.type === "del" ? h("del", { text: p.value }) : document.createTextNode(p.value)))));
  }
  li.append(
    h("div", { class: "row" },
      !failed ? h("button", { type: "button", class: "btn", "aria-pressed": String(!!ctx.diffOn), onclick: ctx.onDiff }, "Diff vs editor") : null,
      !failed && !v.isCurrent ? h("button", { type: "button", class: "btn", onclick: ctx.onRestore }, "Restore") : null,
      h("button", { type: "button", class: "btn", "aria-pressed": String(!!v.starred), onclick: () => ctx.onStar(!v.starred) }, v.starred ? "Unstar" : "Star"),
      v.prompt ? h("button", { type: "button", class: "btn", onclick: () => ctx.onUsePrompt(v.prompt) }, "Use prompt") : null,
    ),
  );
  return li;
}
