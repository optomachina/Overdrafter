async page => {
  const pause = ms => page.waitForTimeout(ms);
  const input = page.getByRole('textbox', {name:'Message', exact:true});
  const history = page.getByRole('button', {name:'Conversation', exact:true});
  const send = async text => { await input.fill(text); await page.getByRole('button', {name:'Send message', exact:true}).click(); };
  await page.getByRole('button', {name:'Before · 5 mm', exact:true}).click();
  await page.locator('canvas').waitFor();
  await pause(1600);
  await page.getByRole('button', {name:'After · 8 mm', exact:true}).click();
  await pause(1600);
  const bounds = await page.locator('canvas').boundingBox();
  await page.mouse.move(bounds.x+bounds.width/2, bounds.y+bounds.height/2);
  await page.mouse.down();
  await page.mouse.move(bounds.x+bounds.width/2+110, bounds.y+bounds.height/2+40, {steps:18});
  await page.mouse.up();
  await page.mouse.wheel(0,-110);
  await pause(1200);
  await input.fill('I want to explore a thicker part.\nKeep the component positions unchanged.\nHelp me compare the result.');
  await pause(1800);
  await send('Make it thicker');
  await page.getByText(/What target depth should the baseline part have/).waitFor();
  await pause(1600);
  await send('7');
  await page.getByText(/Which units do you mean for 7/).waitFor();
  await pause(1300);
  await send('mm');
  await page.getByRole('button', {name:'Evaluate this change',exact:true}).waitFor();
  await pause(1700);
  await page.getByRole('button', {name:'Evaluate this change',exact:true}).click();
  await page.getByRole('button', {name:/04 · 5 → 7 mm/}).waitFor();
  await pause(1500);
  await history.click();
  await page.getByRole('button', {name:'After · 7 mm', exact:true}).click();
  await page.getByText('Waiting for candidate geometry',{exact:true}).waitFor();
  await pause(1800);
  await history.click();
  await page.getByRole('button', {name:/01 · 5 → 8 mm/}).click();
  await pause(1500);
  await history.click();
  await page.getByRole('button', {name:'After · 8 mm', exact:true}).click();
  await pause(2000);
  return 'Recorded exact native comparison and an explicitly pending fourth decision.';
}
